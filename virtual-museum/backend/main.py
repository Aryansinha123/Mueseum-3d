# ── PYDANTIC MODELS ───────────────────────────────────────────────────────────

class AskRequest(BaseModel):
    session_id: Optional[str] = Field(
        default=None,
        description="Anonymous visitor session UUID. Auto-generated by backend if absent."
    )
    question: str = Field(
        ...,
        description="Visitor question text (1–1000 characters)."
    )
    artifact_id: Optional[str] = Field(
        default=None,
        description="ID of the currently selected 3D artifact (e.g. 'ART001'). Enables contextual answers."
    )
    tone: str = Field(
        default="educational",
        description="Curator presentation style: 'educational', 'concise', or 'friendly'."
    )

    @field_validator("question")
    @classmethod
    def validate_question_text(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Question text cannot be empty.")
        if len(v.strip()) > 1000:
            raise ValueError("Question is too long (maximum 1000 characters).")
        return v.strip()

    @field_validator("tone")
    @classmethod
    def validate_tone_setting(cls, v: str) -> str:
        return validate_tone(v)

    @field_validator("artifact_id")
    @classmethod
    def validate_artifact_id(cls, v: Optional[str]) -> Optional[str]:
        if v is None:
            return None
        cleaned = v.strip()
        return cleaned if cleaned else None


class SourcePayload(BaseModel):
    artifact: str
    gallery: str


class SuggestionPayload(BaseModel):
    artifact_id: str
    artifact_name: str
    gallery: str
    similarity: float


class AskResponse(BaseModel):
    answer: str
    source: Optional[SourcePayload] = None
    confidence: float
    evidence: Optional[str] = None
    refused: bool
    session_id: str
    tone: str
    related_suggestions: List[SuggestionPayload] = []


