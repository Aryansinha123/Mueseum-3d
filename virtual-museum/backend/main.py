@app.get("/health", tags=["Health"])
def health_check():
    """Dedicated health probe."""
    return {"status": "healthy"}


@app.post("/ask", response_model=AskResponse, tags=["AI Curator"])
def ask_curator_endpoint(payload: AskRequest):
    """
    Main AI Curator RAG endpoint.

    Accepts a visitor question and optional selected artifact ID.
    Routes through Phase 1 retrieval → Phase 2 threshold → Phase 3 personalization.
    Returns a grounded, source-attributed response or a structured refusal.
    """
    print(f"\n[API DEBUG] Received artifact_id: {payload.artifact_id}")
    print(f"[API DEBUG] Received question: \"{payload.question}\"")
    print(f"[API DEBUG] Session ID: {payload.session_id or '(new session)'}")
    print(f"[API DEBUG] Tone: {payload.tone}")

    try:
        result = answer_question(
            question=payload.question,
            session_id=payload.session_id,
            tone=payload.tone,
            artifact_id=payload.artifact_id,  # Forwarded to RAG pipeline
        )

        resolved_art = result.get("source", {}).get("artifact") if result.get("source") else "None (Refused/General)"
        print(f"[API DEBUG] Resolved artifact: {resolved_art}")
        print(f"[API DEBUG] Refused: {result.get('refused', False)}")
        print(f"[API DEBUG] Confidence: {result.get('confidence', 0.0):.4f}")
        print(f"[API DEBUG] LLM called: {result.get('llm_called', False)}")

        return result

    except ValueError as ve:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(ve),
        )
    except Exception as err:
        # Log full error server-side but do NOT expose stack trace to frontend
        print(f"[API ERROR] Internal error in /ask endpoint: {type(err).__name__}: {err}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An error occurred while processing your query. Please try again.",
        )
